const has = (q, ...ws) => ws.some((w) => q.includes(w));
function zoneInfo(z, ctx) {
  const rel = { 4: 'ต้องอยู่ซ้ายของโซน 3 และใกล้ตาข่ายกว่าโซน 5', 3: 'ต้องอยู่ขวาของโซน 4 ซ้ายของโซน 2 และใกล้ตาข่ายกว่าโซน 6', 2: 'ต้องอยู่ขวาของโซน 3 และใกล้ตาข่ายกว่าโซน 1',
    5: 'ต้องอยู่ซ้ายของโซน 6 และลึกกว่าโซน 4', 6: 'ต้องอยู่ซ้ายของโซน 1 และลึกกว่าโซน 3', 1: 'ต้องอยู่ขวาของโซน 6 และลึกกว่าโซน 2 (เป็นผู้เสิร์ฟ)' }[z];
  const p = ctx.lineup[z] ? ctx.who(ctx.lineup[z]) : null;
  const mine = ctx.faults.filter((f) => f.zones.includes(z));
  return t('โซน {z} = {n} · {r}\nตอนผู้เสิร์ฟตีบอล {rel}', { z, n: t(ZONE_NAME[z]), r: isFront(z) ? t('แนวหน้า') : t('แนวหลัง'), rel: t(rel) }) +
    (p ? '\n' + t('ตอนนี้: #{n} {name}', { n: p.n, name: p.name }) : '\n' + t('ตอนนี้โซนนี้ยังว่าง')) +
    (mine.length ? '\n⚠ ' + mine.map((f) => f.title).join(' / ') : '\n' + t('ตำแหน่งปัจจุบันของโซนนี้ถูกต้อง'));
}
export function answer(q0, ctx) {
  const q = String(q0 || '').toLowerCase();
  const zm = q.match(/(?:โซน|zone)\s*([1-6])/);
  if (zm) return zoneInfo(+zm[1], ctx);
  if (has(q, 'ลิเบอโร', 'libero')) return t('ลิเบอโรใส่เสื้อสีต่างจากทีม เล่นได้เฉพาะแนวหลัง (โซน 5, 6, 1) เข้าแทนมิดเดิลแนวหลังได้ไม่จำกัดครั้ง ห้ามเสิร์ฟ/บล็อก/ตบเหนือตาข่าย เมื่อหมุนมาถึงโซน 4 ต้องออกและให้ผู้เล่นตัวเดิมกลับเข้า (ระบบทำให้อัตโนมัติเมื่อกดหมุน)');
  if (has(q, 'ทำไม', 'ผิด', 'why', 'wrong', 'fault', 'error', 'ไม่ผ่าน')) {
    if (ctx.phase === 'free') return t('ตอนนี้อยู่โหมด “หลังเสิร์ฟ” ซึ่งผู้เล่นยืนอิสระ จึงไม่ตรวจกติกา สลับเป็น “ตอนเสิร์ฟ” เพื่อตรวจ');
    if (!ctx.faults.length) return t('ตอนนี้ไม่พบจุดที่ผิดกติกา ทุกโซนอยู่ในลำดับถูกต้องตอนผู้เสิร์ฟตีบอล');
    return ctx.faults.map((f, i) => `${i + 1}. ${f.title}\n   ${t('เพราะ')}: ${f.why}\n   ${f.fix}`).join('\n\n');
  }
  if (has(q, 'ทับซ้อน', 'overlap', 'กฎการยืน', 'กติกาการยืน', 'ตำแหน่งยืน', 'rule')) return t('กติกายืนทับซ้อม (Overlap) ใช้ตอนผู้เสิร์ฟตีบอล:\n1) แนวหน้าต้องใกล้ตาข่ายกว่าแนวหลังที่คู่กัน (4↔5, 3↔6, 2↔1)\n2) แนวหน้าเรียงซ้าย→ขวา 4-3-2 และแนวหลัง 5-6-1\n3) ลิเบอโรอยู่แนวหลังเท่านั้น\nตัดสินจากตำแหน่งเท้าที่แตะพื้น พอผู้เสิร์ฟตีบอลแล้วทุกคนย้ายได้อิสระ');
  if (has(q, 'หมุน', 'โรเตชัน', 'rotation', 'rotate')) return t('เมื่อทีมได้สิทธิ์เสิร์ฟคืน ต้องหมุนตามเข็มนาฬิกา 4→3→2→1→6→5→4 ผู้เล่นโซน 1 หมุนไปโซน 6 และคนที่ได้เสิร์ฟคือคนที่เข้าโซน 1 ใหม่ ปุ่ม “หมุนตามเข็มนาฬิกา” ทำให้ครบทั้ง 6 คน');
  if (has(q, 'หลังเสิร์ฟ', 'after serve', 'อิสระ', 'free')) return t('กติกาทับซ้อมมีผลเฉพาะ “ขณะผู้เสิร์ฟตีบอล” หลังจากนั้นผู้เล่นย้ายไปยืนที่ไหนก็ได้ จึงมีโหมด “หลังเสิร์ฟ” ให้ลากอิสระโดยไม่เตือน');
  if (has(q, 'เปลี่ยนตัว', 'sub')) return t('เปลี่ยนตัวได้ 6 ครั้งต่อเซ็ต ผู้เล่นที่ออกกลับเข้าได้เฉพาะแทนตำแหน่งเดิมเท่านั้น ลิเบอโรไม่นับเป็นการเปลี่ยนตัว');
  if (has(q, 'เวลานอก', 'timeout', 'time-out')) return t('ขอเวลานอกได้ 2 ครั้งต่อเซ็ต ครั้งละ 30 วินาที (ส่วนใหญ่ของรายการแข่งในไทย) ปุ่มบันทึกเกมสดในหน้า “แมตช์” นับให้อัตโนมัติ');
  if (has(q, 'เสิร์ฟ', 'serve')) return t('ผู้เสิร์ฟคือผู้เล่นโซน 1 เสิร์ฟจากหลังเส้นหลังภายในพื้นที่เสิร์ฟ ถ้าเสิร์ฟสำเร็จทีมได้แต้มและเสิร์ฟต่อ ถ้าเสียแต้มสิทธิ์เสิร์ฟตกเป็นของคู่แข่ง');
  if (has(q, 'รับเสิร์ฟ', 'receive', 'w formation')) return t('ฟอร์มรับเสิร์ฟยอดนิยมคือ “W” 5 คน: แนวหน้า 4 และ 2 ถอยเข้าด้านข้าง โซน 3 ยืนใกล้ตาข่ายเตรียมเป็นเซตเตอร์ หลัง 5-6-1 ยืนเป็นแนวโค้ง ลองกดแท็บ “รับเสิร์ฟ” แล้วลากปรับได้');
  if (has(q, 'ใช้', 'วิธี', 'how', 'help', 'ช่วย', 'ทำยังไง')) return t('วิธีใช้: ลากผู้เล่นบนสนามไปตำแหน่งที่ต้องการ (หรือเลือกแล้วกดลูกศรบนคีย์บอร์ด) ระบบตรวจกติกาให้ทันทีและบอกเหตุผล ใช้ปุ่มตัวอย่างด้านล่างเพื่อดูเคสที่ผิด และถามเรื่องกติกากับผมได้ที่นี่');
  return t('ผมตอบเรื่องกติกาการยืน การหมุน ลิเบอโร และตำแหน่งแต่ละโซนได้ ลองถามว่า “ทำไมตอนนี้ผิดตำแหน่ง” หรือ “โซน 3 ต้องยืนยังไง” หรือกดคำถามตัวอย่างด้านล่าง');
}
