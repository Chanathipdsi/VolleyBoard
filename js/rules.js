/* positions of a formation with the coach's custom drags applied */
export function posOf(court, form) {
  const base = (FORMS[form] || FORMS.base).pts, c = (court.custom && court.custom[form]) || {}, out = {};
  ZONES.forEach((z) => { out[z] = c[z] ? [c[z][0], c[z][1]] : base[z].slice(); });
  return out;
}

const DEPTH = [[4, 5], [3, 6], [2, 1]];
const LATERAL = [[4, 3], [3, 2], [5, 6], [6, 1]];
export function check(pos, lineup, who) {
  const label = (z) => { const p = lineup[z] ? who(lineup[z]) : null; return t('โซน {z}', { z }) + (p ? ` (#${p.n} ${p.name})` : ''); };
  const faults = [], bad = {};
  const add = (f) => { faults.push(f); f.zones.forEach((z) => { bad[z] = true; }); };
  DEPTH.forEach(([f, b]) => {
    if (pos[f][1] >= pos[b][1]) add({ kind: 'depth', zones: [f, b], title: t('{a} ยืนลึกกว่า {b}', { a: label(f), b: label(b) }),
      why: t('ตอนผู้เสิร์ฟตีบอล ผู้เล่นแนวหน้าต้องมีเท้าใกล้ตาข่ายกว่าผู้เล่นแนวหลังที่อยู่คู่กัน (4↔5, 3↔6, 2↔1) ถ้าลึกกว่าหรือเสมอกันถือว่ายืนผิดตำแหน่ง ทีมเสียแต้มและคู่แข่งได้เสิร์ฟ'),
      fix: t('แก้: ลากโซน {f} ให้ขึ้นไปใกล้ตาข่ายกว่าโซน {b}', { f, b }) });
  });
  LATERAL.forEach(([l, r]) => {
    if (pos[l][0] >= pos[r][0]) add({ kind: 'lateral', zones: [l, r], title: t('{a} ต้องอยู่ซ้ายของ {b}', { a: label(l), b: label(r) }),
      why: isFront(l) ? t('ผู้เล่นแนวหน้าต้องเรียงจากซ้ายไปขวาเป็น 4 → 3 → 2 ตามลำดับการหมุน ห้ามสลับฝั่งกันก่อนเสิร์ฟ') : t('ผู้เล่นแนวหลังต้องเรียงจากซ้ายไปขวาเป็น 5 → 6 → 1 ตามลำดับการหมุน ห้ามสลับฝั่งกันก่อนเสิร์ฟ'),
      fix: t('แก้: ลากโซน {l} ไปทางซ้ายของโซน {r}', { l, r }) });
  });
  [2, 3, 4].forEach((z) => {
    const p = lineup[z] ? who(lineup[z]) : null;
    if (p && p.pos === 'L') add({ kind: 'libero', zones: [z], title: t('ลิเบอโรอยู่แนวหน้า ({a})', { a: label(z) }),
      why: t('ลิเบอโรเล่นได้เฉพาะแนวหลัง (โซน 5, 6, 1) จึงอยู่โซน 2, 3, 4 ไม่ได้ เมื่อหมุนมาถึงโซน 4 ต้องให้ผู้เล่นตัวเดิมกลับเข้าแทน'),
      fix: t('แก้: กด “ลิเบอโรออก” หรือสลับลิเบอโรไปแนวหลัง') });
  });
  return { faults, bad };
}

